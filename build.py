import os
import re
import sys
import subprocess
import platform
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent / "src"))
import app_info  # noqa: E402 - needs the sys.path tweak above

ROOT_DIR = Path(__file__).parent
SRC_DIR = ROOT_DIR / "src"
# Written by --version and imported by src/app_info.py. Generated, gitignored.
BUILD_VERSION_FILE = SRC_DIR / "_build_version.py"


qt_plugins = [
    "platforms",
    "styles",
    "iconengines",
    "imageformats",
]


def resource_version(version: str) -> str:
    """Numeric a.b.c[.d] form for Nuitka's --file-version/--product-version.

    Nuitka rejects anything else, and CI's non-tag path produces versions like
    ``dev-20260823-a1b2c3d``. Those still go into _build_version.py verbatim so
    the About box and log identify the build; only the Windows version resource
    falls back.
    """
    match = re.match(r"^v?(\d+(?:\.\d+){0,3})$", version.strip())
    if match:
        return match.group(1)
    return app_info.APP_VERSION_FALLBACK


def write_build_version(version: str) -> None:
    """Bake the release version into the tree app_info reads from.

    Without this, APP_VERSION was whatever literal happened to be in
    app_info.py, so a binary built from tag v1.3.0 still reported 1.1.0 - and
    the update checker compared the *latest release tag* against that stale
    number and offered the same "update" on every single launch, forever.
    """
    BUILD_VERSION_FILE.write_text(
        '"""Generated by build.py - do not edit, do not commit."""\n\n'
        f'BUILD_VERSION = "{version}"\n',
        encoding="utf-8",
    )
    print(f"Stamped build version: {version} -> {BUILD_VERSION_FILE.name}")


def translation_data_args() -> list:
    """Ship the compiled gettext catalogs next to the executable.

    utilities.functions.get_lang_dir() looks for ``<exe dir>/lang`` when
    frozen. Nothing was ever including that directory, so every built copy of
    the app fell back to untranslated English no matter what language the user
    picked in Preferences.
    """
    lang_dir = ROOT_DIR / "lang"
    if not lang_dir.is_dir():
        print("  [warn] lang/ not found - the build will have no translations.")
        return []
    if not any(lang_dir.rglob("*.mo")):
        print("  [warn] lang/ contains no compiled .mo catalogs - run "
              "scripts/compile_lang.py before building for translations to work.")
    return [f"--include-data-dir={lang_dir}=lang"]


def compile_resources():
    assets_dir = Path(__file__).parent / "assets"
    src_dir = Path(__file__).parent / "src"
    qrc_file = assets_dir / "resources.qrc"
    output_file = src_dir / "resources_rc.py"
    
    if not qrc_file.exists():
        print("Error: resources.qrc not found in assets directory")
        return False
    
    try:
        print("Compiling Qt resources...")
        subprocess.run([
            "pyside6-rcc", 
            str(qrc_file), 
            "-o", 
            str(output_file)
        ], check=True)
        print("Resources compiled successfully!")
        return True
    except subprocess.CalledProcessError as e:
        print(f"Resource compilation failed: {e}")
        return False
    except FileNotFoundError:
        print("Error: pyside6-rcc not found. Make sure PySide6 is installed.")
        return False


def build_executable(version: str | None = None):
    src_dir = Path(__file__).parent / "src"
    app_file = src_dir / "app.py"
    assets_dir = Path(__file__).parent / "assets"

    if not app_file.exists():
        print("Error: app.py not found in src directory")
        return False

    if not compile_resources():
        return False

    if version:
        write_build_version(version)
    else:
        version = app_info.APP_VERSION

    res_version = resource_version(version)
    if res_version != version:
        print(f"Version resource stamped as {res_version} (from '{version}')")

    current_platform = platform.system().lower()

    nuitka_args = [
        sys.executable, "-m", "nuitka",
        "--standalone",
        "--deployment",
        "--no-debug-immortal-assumptions",
        "--enable-plugin=pyside6",
        f"--include-qt-plugins={','.join(qt_plugins)}",
        "--report=compilation-report.xml",
        f"--output-dir={Path(__file__).parent / 'dist'}",
        # Embed the real app identity (see src/app_info.py) into the built
        # binary's version info / bundle metadata, instead of Nuitka's
        # defaults - this is what shows up in Explorer's file properties
        # dialog / Finder's Get Info, and is what the Windows/macOS
        # installers below present as the app's publisher.
        f"--company-name={app_info.APP_PUBLISHER}",
        f"--product-name={app_info.APP_NAME}",
        f"--file-version={res_version}",
        f"--product-version={res_version}",
        f"--copyright={app_info.APP_COPYRIGHT}",
        f"--file-description={app_info.APP_DESCRIPTION}",
    ]
    nuitka_args.extend(translation_data_args())

    if current_platform == "windows":
        icon_file = assets_dir / "photon-snapshot.ico"
        nuitka_args.extend([
            "--windows-console-mode=disable",
            "--assume-yes",
            "--output-filename=PhotonSnapshot.exe",
        ])
        if icon_file.exists():
            nuitka_args.append(f"--windows-icon-from-ico={icon_file}")

    elif current_platform == "darwin":
        icon_file = assets_dir / "photon-snapshot.icns"
        nuitka_args.extend([
            "--macos-create-app-bundle",
            "--macos-app-name=PhotonSnapshot",
        ])
        if icon_file.exists():
            nuitka_args.append(f"--macos-app-icon={icon_file}")
        nuitka_args.append(f"--macos-app-version={res_version}")

    else:
        nuitka_args.append("--output-filename=PhotonSnapshot")
    
    nuitka_args.append(str(app_file))
    
    try:
        print(f"Building executable with Nuitka for {current_platform}...")
        print(f"Command: {' '.join(nuitka_args)}")
        result = subprocess.run(nuitka_args, check=True)
        print("Build completed successfully!")
        return True
    except subprocess.CalledProcessError as e:
        print(f"Build failed: {e}")
        return False
    except FileNotFoundError:
        print("Error: Nuitka not found. Install with: pip install nuitka")
        return False


def install_requirements():
    requirements_file = Path(__file__).parent / "requirements.txt"
    
    if not requirements_file.exists():
        print("Error: requirements.txt not found")
        return False
    
    try:
        print("Installing requirements...")
        subprocess.run([sys.executable, "-m", "pip", "install", "-r", str(requirements_file)], check=True)
        print("Requirements installed successfully!")
        return True
    except subprocess.CalledProcessError as e:
        print(f"Failed to install requirements: {e}")
        return False


def main():
    args = sys.argv[1:]

    if "--install" in args:
        install_requirements()
        return

    version = None
    for arg in args:
        if arg.startswith("--version="):
            version = arg.split("=", 1)[1].strip().lstrip("vV")
        elif arg in ("-h", "--help"):
            print("Photon Snapshot Build Script")
            print("Usage:")
            print("  python build.py --install         Install requirements")
            print("  python build.py                   Build using the version in src/app_info.py")
            print("  python build.py --version=1.2.0   Build and stamp this version into the binary")
            return
        else:
            print(f"Unknown argument: {arg}")
            return

    print("Photon Snapshot Build Script")
    print()
    build_executable(version)


if __name__ == "__main__":
    main()