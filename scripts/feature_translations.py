def apply(fr, es, ar):
    dictionaries = fr, es, ar
    rows = [line.split('|') for line in ROWS.splitlines() if line] + LONG_ROWS
    for source, *translations in rows:
        for dictionary, translated in zip(dictionaries, translations):
            dictionary[source] = translated
            if not source.endswith((':', ' ', '.', '?')):
                for suffix in (':', '...', '…'):
                    dictionary[source + suffix] = translated + suffix
